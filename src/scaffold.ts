import { execFile } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { promisify } from "node:util";

const execFileAsync = promisify(execFile);

interface BlueprintSelections {
    selectedPages?: string[];
    selectedFeatures?: string[];
    selectedIntegrations?: string[];
    selectedLocales?: string[];
    selectedRoles?: string[];
    selectedBrandTones?: string[];
    selectedVisualStyles?: string[];
    selectedContentModels?: string[];
    selectedSEOFocuses?: string[];
}

interface Blueprint {
    id?: string;
    createdAt?: string;
    projectName?: string;
    slug?: string;
    selections?: BlueprintSelections;
}

interface ScaffoldOptions {
    blueprintPath: string;
    outRoot?: string;
    initGit?: boolean;
}

const DEFAULT_OUT_ROOT = "/Users/waelio/Code/GitHub/waelio/siteforge/sites";

function slugify(value: string): string {
    return value
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/^-+|-+$/g, "")
        || "site";
}

function pageToRoute(name: string): string {
    const trimmed = name.trim();
    if (!trimmed || trimmed.toLowerCase() === "home") return "/";
    return "/" + slugify(trimmed);
}

function pagePath(route: string): string {
    if (route === "/") return "app/page.tsx";
    return `app${route}/page.tsx`;
}

async function writeFileEnsured(filePath: string, content: string): Promise<void> {
    await mkdir(path.dirname(filePath), { recursive: true });
    await writeFile(filePath, content, "utf8");
}

