export interface ScaffoldResult {
    slug: string;
    outDir: string;
    pageCount: number;
}

async function pathExists(target: string): Promise<boolean> {
    try {
        await stat(target);
        return true;
    } catch {
        return false;
    }
}

async function uniqueOutDir(outRoot: string, slug: string): Promise<string> {
    const base = path.join(outRoot, slug);
    if (!(await pathExists(base))) return base;
    for (let i = 2; i < 1000; i++) {
        const candidate = path.join(outRoot, `${slug}-${i}`);
        if (!(await pathExists(candidate))) return candidate;
    }
    throw new Error(`Unable to find a free output directory for slug "${slug}"`);
}

export async function scaffoldFromBlueprint(
    options: ScaffoldFromBlueprintOptions,
): Promise<ScaffoldResult> {
    const blueprint = options.blueprint;
    const projectName = blueprint.projectName?.trim() || "Siteforge Project";
    const slugBase = slugify(blueprint.slug || projectName);
    const outRoot = options.outRoot || DEFAULT_OUT_ROOT;
    const outDir = await uniqueOutDir(outRoot, slugBase);
    const slug = path.basename(outDir);

    return writeScaffold(blueprint, projectName, slug, outDir, options.initGit);
}

export async function scaffold(options: ScaffoldOptions): Promise<ScaffoldResult> {
    const raw = await readFile(options.blueprintPath, "utf8");
    const blueprint = JSON.parse(raw) as Blueprint;

    return scaffoldFromBlueprint({
        blueprint,
        outRoot: options.outRoot,
        initGit: options.initGit,
    });
}

async function writeScaffold(
    blueprint: Blueprint,
    projectName: string,
    slug: string,
    outDir: string,
    initGit: boolean | undefined,
): Promise<ScaffoldResult> {

    const sel = blueprint.selections ?? {};
    const pageNames = Array.from(
        new Set([
            "Home",
            ...(sel.selectedPages ?? []),
        ]),
    );
    const pages = pageNames.map((name) => ({ name, route: pageToRoute(name) }));

    const integrations = (sel.selectedIntegrations ?? []).map(x => x.toLowerCase());
    let framework: "next" | "vue" | "react" | "svelte" | "angular" = "next";
    
    if (integrations.includes("vue")) framework = "vue";
    else if (integrations.includes("svelte")) framework = "svelte";
    else if (integrations.includes("angular")) framework = "angular";
    else if (integrations.includes("react") && !integrations.includes("next.js")) framework = "react";

    if (framework === "next") {
        // Next.js Frontend
        await writeFileEnsured(
            path.join(outDir, "frontend/package.json"),
            frontendPackageJson(slug),
        );
        await writeFileEnsured(
            path.join(outDir, "frontend/tsconfig.json"),
            NEXT_TSCONFIG,
        );
        await writeFileEnsured(
            path.join(outDir, "frontend/next.config.js"),
            NEXT_CONFIG,
        );
        await writeFileEnsured(
            path.join(outDir, "frontend/next-env.d.ts"),
            NEXT_ENV_DTS,
        );
        await writeFileEnsured(
            path.join(outDir, "frontend/app/layout.tsx"),
            rootLayout(projectName, pages),
        );

        for (const page of pages) {
            await writeFileEnsured(
                path.join(outDir, "frontend", pagePath(page.route)),
                pageComponent(page.name, projectName),
            );
        }
    } else {
        // Multi-framework Frontend
        try {
            const pkgPath = path.join(TEMPLATES_DIR, `package.${framework}.json`);
            let pkgData = await readFile(pkgPath, "utf8");
            
            // Render package.json
            pkgData = pkgData.replace(/"name":\s*"[^"]+"/, `"name": "${slug}-frontend"`);
            await writeFileEnsured(path.join(outDir, "frontend/package.json"), pkgData);

            const extMap: Record<string, string> = {
                vue: "vue",
                react: "tsx",
                svelte: "svelte",
                angular: "component.ts"
            };
            const ext = extMap[framework];
            const tplPath = path.join(TEMPLATES_DIR, `index.${ext}`);
            let tplData = await readFile(tplPath, "utf8");

            // Render template placeholders
            tplData = tplData
                .replace(/\{\{\s*title\s*\}\}/g, projectName)
                .replace(/\{\{\s*email\s*\}\}/g, `${slug}@example.com`)
                .replace(/\{\{\s*description\s*\}\}/g, `Generated frontend for ${projectName}`);

            // For simplicity, just create an App/index file since the templates are single components
            const srcPath = path.join(outDir, "frontend/src", `App.${ext}`);
            await writeFileEnsured(srcPath, tplData);
        } catch (e) {
            console.warn(`Failed to scaffold ${framework} frontend, falling back to empty dir: ${e}`);
        }
    }
    // Backend
    const features = sel.selectedFeatures ?? [];
    const modules = ["Health", ...features];
    await writeFileEnsured(
        path.join(outDir, "backend/package.json"),
        backendPackageJson(slug),
    );
    await writeFileEnsured(
        path.join(outDir, "backend/tsconfig.json"),
        NEST_TSCONFIG,
    );
    await writeFileEnsured(
        path.join(outDir, "backend/src/main.ts"),
        nestMain(modules),
    );
    await writeFileEnsured(
        path.join(outDir, "backend/src/app.module.ts"),
        nestAppModule(features),
    );
    await writeFileEnsured(
        path.join(outDir, "backend/src/health.controller.ts"),
        NEST_HEALTH_CONTROLLER,
    );

    for (const feature of features) {
        const routeName = slugify(feature);
        const featureDir = path.join(outDir, "backend/src", routeName);
        await writeFileEnsured(
            path.join(featureDir, `${routeName}.service.ts`),
            nestFeatureService(feature)
        );
        await writeFileEnsured(
            path.join(featureDir, `${routeName}.controller.ts`),
            nestFeatureController(feature)
        );
        await writeFileEnsured(
            path.join(featureDir, `${routeName}.module.ts`),
            nestFeatureModule(feature)
        );
    }

    // Root
    await writeFileEnsured(
        path.join(outDir, "README.md"),
        rootReadme(projectName, slug, blueprint),
    );
    await writeFileEnsured(
        path.join(outDir, ".gitignore"),
        ROOT_GITIGNORE,
    );
    await writeFileEnsured(
        path.join(outDir, "blueprint.json"),
        JSON.stringify(blueprint, null, 2),
    );

    if (initGit !== false) {
        try {
            await execFileAsync("git", ["init", "-q"], { cwd: outDir });
            await execFileAsync("git", ["add", "."], { cwd: outDir });
            await execFileAsync(
                "git",
                ["commit", "-q", "-m", "scaffold from siteforge blueprint"],
                {
                    cwd: outDir,
                    env: {
                        ...process.env,
                        GIT_AUTHOR_NAME: process.env.GIT_AUTHOR_NAME ?? "waelio-cli",
                        GIT_AUTHOR_EMAIL:
                            process.env.GIT_AUTHOR_EMAIL ?? "cli@waelio.dev",
                        GIT_COMMITTER_NAME:
                            process.env.GIT_COMMITTER_NAME ?? "waelio-cli",
                        GIT_COMMITTER_EMAIL:
                            process.env.GIT_COMMITTER_EMAIL ?? "cli@waelio.dev",
                    },
                },
            );
        } catch (err) {
            // Non-fatal: leave folder unversioned if git init fails.
            console.warn(
                `git init skipped: ${err instanceof Error ? err.message : String(err)}`,
            );
        }
    }

    return { slug, outDir, pageCount: pages.length };
}
