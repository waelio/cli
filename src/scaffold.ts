function rootLayout(name: string, pages: { name: string; route: string }[]): string {
    const navItems = pages
        .map((p) => `<a href="${p.route}" style={{ marginRight: 16 }}>${p.name}</a>`)
        .join("\n          ");

    return `import type { ReactNode } from "react";

export const metadata = {
  title: "${name}",
  description: "Generated by waelio/cli + siteforge",
};

export default function RootLayout({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <body style={{ fontFamily: "system-ui, sans-serif", margin: 0 }}>
        <header style={{ padding: 16, borderBottom: "1px solid #eee" }}>
          <strong>${name}</strong>
          <nav style={{ marginTop: 8 }}>
          ${navItems}
          </nav>
        </header>
        <main style={{ padding: 24 }}>{children}</main>
      </body>
    </html>
  );
}
`;
}

function pageComponent(pageName: string, projectName: string): string {
    const isHome = pageName.toLowerCase() === "home" || pageName === "/";
    const heading = isHome ? projectName : pageName;
    return `export default function Page() {
  return (
    <section>
      <h1>${heading}</h1>
      <p>Generated ${pageName} page.</p>
    </section>
  );
}
`;
}

