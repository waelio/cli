function rootReadme(name: string, slug: string, blueprint: Blueprint): string {
    const sel = blueprint.selections ?? {};
    const list = (xs?: string[]) =>
        xs && xs.length ? xs.map((x) => `- ${x}`).join("\n") : "_(none)_";
    return `# ${name}

Generated by **waelio/cli** from a siteforge blueprint.

- **Slug:** \`${slug}\`
- **Generated:** ${new Date().toISOString()}

## Layout

- \`frontend/\` — Next.js app (port 3001)
- \`backend/\` — NestJS app (port 3002)

## Run

\`\`\`bash
cd frontend && npm install && npm run dev
cd ../backend && npm install && npm run start:dev
\`\`\`

## Blueprint selections

### Pages
${list(sel.selectedPages)}

### Features
${list(sel.selectedFeatures)}

### Integrations
${list(sel.selectedIntegrations)}

### Locales
${list(sel.selectedLocales)}

### Roles
${list(sel.selectedRoles)}
`;
}

const ROOT_GITIGNORE = `node_modules/
dist/
.next/
.env
.env.local
*.log
`;

export interface ScaffoldResult {
    slug: string;
    outDir: string;
    pageCount: number;
}

export async function scaffold(options: ScaffoldOptions): Promise<ScaffoldResult> {
    const raw = await readFile(options.blueprintPath, "utf8");
    const blueprint = JSON.parse(raw) as Blueprint;

    const projectName = blueprint.projectName?.trim() || "Siteforge Project";
    const slug = slugify(blueprint.slug || projectName);
    const outRoot = options.outRoot || DEFAULT_OUT_ROOT;
    const outDir = path.join(outRoot, slug);

    const sel = blueprint.selections ?? {};
    const pageNames = Array.from(
        new Set([
            "Home",
            ...(sel.selectedPages ?? []),
        ]),
    );
    const pages = pageNames.map((name) => ({ name, route: pageToRoute(name) }));

    // Frontend
    await writeFileEnsured(
        path.join(outDir, "frontend/package.json"),
        frontendPackageJson(slug),
    );
    await writeFileEnsured(
        path.join(outDir, "frontend/tsconfig.json"),
        NEXT_TSCONFIG,
    );
    await writeFileEnsured(
        path.join(outDir, "frontend/next.config.js"),
        NEXT_CONFIG,
    );
    await writeFileEnsured(
        path.join(outDir, "frontend/next-env.d.ts"),
        NEXT_ENV_DTS,
    );
    await writeFileEnsured(
        path.join(outDir, "frontend/app/layout.tsx"),
        rootLayout(projectName, pages),
    );

    for (const page of pages) {
        await writeFileEnsured(
            path.join(outDir, "frontend", pagePath(page.route)),
            pageComponent(page.name, projectName),
        );
    }

    // Backend
    const features = sel.selectedFeatures ?? [];
    const modules = ["Health", ...features];
    await writeFileEnsured(
        path.join(outDir, "backend/package.json"),
        backendPackageJson(slug),
    );
    await writeFileEnsured(
        path.join(outDir, "backend/tsconfig.json"),
        NEST_TSCONFIG,
    );
    await writeFileEnsured(
        path.join(outDir, "backend/src/main.ts"),
        nestMain(modules),
    );
    await writeFileEnsured(
        path.join(outDir, "backend/src/app.module.ts"),
        NEST_APP_MODULE,
    );
    await writeFileEnsured(
        path.join(outDir, "backend/src/health.controller.ts"),
        NEST_HEALTH_CONTROLLER,
    );

    // Root
    await writeFileEnsured(
        path.join(outDir, "README.md"),
        rootReadme(projectName, slug, blueprint),
    );
    await writeFileEnsured(
        path.join(outDir, ".gitignore"),
        ROOT_GITIGNORE,
    );
    await writeFileEnsured(
        path.join(outDir, "blueprint.json"),
        JSON.stringify(blueprint, null, 2),
    );

    if (options.initGit !== false) {
        try {
            await execFileAsync("git", ["init", "-q"], { cwd: outDir });
            await execFileAsync("git", ["add", "."], { cwd: outDir });
            await execFileAsync(
                "git",
                ["commit", "-q", "-m", "scaffold from siteforge blueprint"],
                {
                    cwd: outDir,
                    env: {
                        ...process.env,
                        GIT_AUTHOR_NAME: process.env.GIT_AUTHOR_NAME ?? "waelio-cli",
                        GIT_AUTHOR_EMAIL:
                            process.env.GIT_AUTHOR_EMAIL ?? "cli@waelio.dev",
                        GIT_COMMITTER_NAME:
                            process.env.GIT_COMMITTER_NAME ?? "waelio-cli",
                        GIT_COMMITTER_EMAIL:
                            process.env.GIT_COMMITTER_EMAIL ?? "cli@waelio.dev",
                    },
                },
            );
        } catch (err) {
            // Non-fatal: leave folder unversioned if git init fails.
            console.warn(
                `git init skipped: ${err instanceof Error ? err.message : String(err)}`,
            );
        }
    }

    return { slug, outDir, pageCount: pages.length };
}
