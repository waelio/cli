function slugify(value: string): string {
    return value
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/^-+|-+$/g, "")
        || "site";
}

function pascalCase(str: string): string {
    return slugify(str).split("-").map(w => w.charAt(0).toUpperCase() + w.slice(1)).join("");
}

function camelCase(str: string): string {
    const p = pascalCase(str);
    return p ? p.charAt(0).toLowerCase() + p.slice(1) : "";
}

function pageToRoute(name: string): string {
    const trimmed = name.trim();
    if (!trimmed || trimmed.toLowerCase() === "home") return "/";
    return "/" + slugify(trimmed);
}

function pagePath(route: string): string {
    if (route === "/") return "app/page.tsx";
    return `app${route}/page.tsx`;
}

async function writeFileEnsured(filePath: string, content: string): Promise<void> {
    await mkdir(path.dirname(filePath), { recursive: true });
    await writeFile(filePath, content, "utf8");
}

